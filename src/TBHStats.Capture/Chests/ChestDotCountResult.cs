namespace TBHStats.Capture.Chests;

/// <summary>
/// Результат визуального подсчёта заполненных точек в ROI-полосе сундука.
/// </summary>
/// <param name="Count">
/// Число обнаруженных заполненных (тёмных) точек. Равно 0, если точек нет
/// или <paramref name="Detected"/> равен <c>false</c>.
/// </param>
/// <param name="Detected">
/// <c>true</c> — обнаружен валидный паттерн точек (есть хотя бы одна светлая/белая
/// незаполненная ячейка или хотя бы одна заполненная тёмная ячейка с корректной
/// структурой run-ов). <c>false</c> — паттерн не распознан (например, ROI попал
/// на тёмный игровой фон без панели сундуков) — счёт не достоверен, поле
/// следует пропустить вышестоящему слою.
/// </param>
public readonly record struct ChestDotCountResult(int Count, bool Detected);
