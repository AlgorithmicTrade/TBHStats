namespace TBHStats.Core.Models;

/// <summary>
/// Определяет, какой набор данных используется при ранжировании и рекомендации этапов (FR-009, FR-019).
/// Введён в уточнении 2026-05-31: сила отряда растёт со временем,
/// поэтому усреднение по всей истории искажает рекомендацию.
/// </summary>
public enum AggregationScope
{
    /// <summary>
    /// Ранжирование по свежему окну — последним <see cref="OptimizationProfile.RecentWindowSize"/>
    /// non-partial забегам на этап (дефолт).
    /// Отражает актуальную силу отряда.
    /// </summary>
    Recent,

    /// <summary>
    /// Ранжирование по всей истории non-partial забегов (all-time).
    /// Используется справочно: сравнение прогресса и трендов.
    /// </summary>
    AllTime,
}
